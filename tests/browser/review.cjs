const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({httpCredentials:{username:'operator',password:'synthetic-browser-only'}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.REVIEW_URL||'http://127.0.0.1:18081');
 await page.getByText('Synthetic browser fixture',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Identify / correct detained outputs'}).first().click();
 await page.locator('#review[open]').waitFor();
 assert.match(await page.locator('[data-source="0"] legend').innerText(),/56:54/);
 assert.match(await page.locator('[data-source="0"]').innerText(),/actual extracted/);
 assert.equal(await page.locator('#short-clips').getAttribute('open'),null);
 assert.equal(await page.locator('#short-clips [data-source]').count(),7);
 assert.deepEqual(await page.locator('#assignments > fieldset').evaluateAll(rows=>rows.map(r=>Number(r.dataset.source))),[0,3,4,6]);
 await page.locator('#short-clips > summary').click();
 await page.locator('[data-source="1"] [data-role]').selectOption('extra');
 await page.locator('[data-source="1"] [data-title]').fill('Manual Extra');
 await page.request.post((process.env.REVIEW_URL||'http://127.0.0.1:18081')+'/__test__/stale-assignment');
 page.once('dialog',dialog=>dialog.accept());
 await page.locator('[data-confirm="cedar/s1d3"]').click();
 await page.waitForFunction(()=>document.querySelector('[data-field="disc"]').value==='3');
 assert.equal(await page.locator('[data-source="0"] [data-number]').inputValue(),'9');
 assert.equal(await page.locator('[data-source="1"] [data-role]').inputValue(),'');
 assert.match(await page.locator('#proposals').innerText(),/S01E09 - Arrival.mkv/);
 assert.match(await page.locator('#mapping-basis').innerText(),/assumption/);
 await page.reload();await page.getByRole('button',{name:'Identify / correct detained outputs'}).first().click();
 assert.equal(await page.locator('[data-field="disc"]').inputValue(),'3');
 await page.locator('[data-reject="cedar/s1d1"]').click();
 await page.locator('[data-reconsider="cedar/s1d1"]').waitFor({state:'attached'});
 assert.equal(await page.locator('[data-confirm="cedar/s1d1"]').count(),0);
 await page.locator('[data-source="0"] [data-number]').fill('10');
 await page.locator('[data-source="3"] [data-number]').fill('9');
 await page.route('**/preview',async route=>{await new Promise(r=>setTimeout(r,600));await route.continue();});
 await page.getByRole('button',{name:'Preview final names',exact:true}).click();
 await page.locator('[data-source="0"] [data-number]').fill('11');
 await page.waitForTimeout(900);
 assert.equal(await page.locator('#submit').isDisabled(),true);
 await page.unroute('**/preview');
 await page.locator('[data-source="0"] [data-number]').fill('10');
 await page.getByRole('button',{name:'Preview final names',exact:true}).click();
 assert.match(await page.locator('#proposals').innerText(),/S01E10 - Wunder.mkv/);
 await page.getByRole('button',{name:'Submit correction & release completed outputs',exact:true}).click();
 await page.locator('#review').waitFor({state:'hidden'});
 const state=await (await page.request.get((process.env.REVIEW_URL||'http://127.0.0.1:18081')+'/api/state')).json();
 assert.equal(state.cycles[0].sources.filter(s=>s.state==='released').length,4);
 assert.equal(state.cycles[0].state,'partially_released');
 assert.equal(errors.length,0,errors.join('\n'));
 await page.screenshot({path:process.env.REVIEW_SCREENSHOT||'/tmp/review-browser.png',fullPage:true});
 await browser.close();console.log('Rendered Chromium review flow passed: duration, grouping, confirmation, persistence, rejection, edits, previews, partial release.');
})().catch(e=>{console.error(e);process.exit(1)});
